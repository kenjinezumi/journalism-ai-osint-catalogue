#!/usr/bin/env python3
"""Build the interactive directory table for the local HTML preview.

Reads docs/directory.json — generated by build.py from records/*.json in the same
build as the markdown directory — so the preview table and the README table can
never describe different projects.

Progressive enhancement: the table is emitted as complete static HTML with every
row present and every cell filled. The filter controls are emitted with the
`hidden` attribute and are revealed by the inline script, so with JavaScript off
the page is an ordinary, fully readable table. No external scripts, styles,
fonts or network calls are involved.
"""
import html
import json

COST_FILTERS = [
    ("nofee", "No software fee", "The project's own software has no fee"),
    ("freetier", "Free tier or threshold",
     "A free tier, or free below a vendor revenue/funding threshold"),
    ("paid", "Paid software", "A fee is required, or the price is quote-only"),
    ("mandatory", "Mandatory paid dependency",
     "A paid API, dataset, model or tool is required for the core function"),
    ("unknown", "Unknown / not verified", "The records do not establish a price"),
]

SORTS = [("rank", "Overall rank"), ("name", "Project name"),
         ("score", "Weighted score"), ("licence_type", "Licence classification"),
         ("oss_status", "Open-source status"), ("price_class", "Software price"),
         ("maintenance_status", "Maintenance"), ("segment", "Category")]


def e(x):
    return html.escape(str(x), quote=True)


def cost_keys(p):
    """Which cost filters a project satisfies. Deliberately overlapping: a project
    with no software fee can still require a paid dependency, and both must match."""
    k = []
    pc = p["price_class"]
    if pc == "No software fee":
        k.append("nofee")
    if pc in ("Free tier", "No fee below threshold"):
        k.append("freetier")
    if pc in ("Paid", "Quote required"):
        k.append("paid")
    if pc == "Unknown / not verified":
        k.append("unknown")
    if "mandatory-paid" in p["cost_flags"]:
        k.append("mandatory")
    return k


def price_cell(p):
    note = p["software_price_note"]
    out = f'<strong>{e(p["price_class"])}</strong>'
    if note:
        out += f' — {e(note)}'
    return out


def cost_cell(p):
    note = p["additional_costs_note"]
    if "mandatory-paid" in p["cost_flags"]:
        return f'<strong class="mand">Mandatory paid dependency</strong> — {e(note)}'
    if not note:
        return "Not recorded"
    return e(note[0].upper() + note[1:])


def controls(d):
    v = d["vocabularies"]
    n = d["count"]
    o = ['<div class="dirtools" id="dirtools" hidden>']
    o.append('<div class="dirrow">')
    o.append('<label class="grow"><span>Search</span>'
             '<input type="search" id="q" placeholder="name, description, licence, '
             'maintainer, category, project ID" autocomplete="off"></label>')
    o.append('</div>')

    def sel(sid, label, options, all_option=True):
        s = [f'<label><span>{e(label)}</span><select id="{sid}">']
        if all_option:
            s.append('<option value="">All</option>')
        for val, lab in options:
            s.append(f'<option value="{e(val)}">{e(lab)}</option>')
        s.append('</select></label>')
        return "".join(s)

    o.append('<div class="dirrow">')
    o.append(sel("f-pillar", "Pillar", [(k, v["pillars"][k]) for k in v["pillars"]]))
    o.append(sel("f-segment", "Category (segment)",
                 [(k, v["segments"][k]) for k in v["segments"]]))
    o.append('</div><div class="dirrow">')
    o.append(sel("f-oss", "Open-source status", [(k, k) for k in v["oss_status"]]))
    o.append(sel("f-maint", "Maintenance", [(k, k) for k in v["maintenance_status"]]))
    o.append(sel("f-sort", "Sort by", SORTS, all_option=False))
    o.append('<label><span>Direction</span><select id="f-dir">'
             '<option value="asc">Ascending</option>'
             '<option value="desc">Descending</option></select></label>')
    o.append('</div>')
    o.append('<fieldset class="costset"><legend>Licence and cost conditions'
             ' <span class="hint">(tick several — conditions overlap, and a project '
             'matching any ticked box is shown)</span></legend>')
    # Each box carries its match count, so a category with no projects reads as a
    # fact about the catalogue rather than as a broken control.
    tally = {k: 0 for k, _l, _t in COST_FILTERS}
    for p in d["projects"]:
        for k in cost_keys(p):
            tally[k] += 1
    unres = sum(1 for p in d["projects"]
                if p["licence_type"] == "Unresolved" or p["oss_status"] == "Unverified")
    for key, label, title in COST_FILTERS:
        o.append(f'<label class="chk" title="{e(title)}">'
                 f'<input type="checkbox" class="costchk" value="{e(key)}"> {e(label)}'
                 f' <span class="n">{tally[key]}</span></label>')
    o.append('<label class="chk" title="Licence classification could not be confirmed, '
             'or open-source status is unverified">'
             '<input type="checkbox" id="f-licunres"> Unresolved licence'
             f' <span class="n">{unres}</span></label>')
    o.append('</fieldset>')
    o.append('<div class="dirrow actions">'
             '<button type="button" id="reset">Reset all filters</button>'
             f'<span class="count" id="count" role="status">Showing {n} of {n} projects</span>'
             '</div>')
    o.append('</div>')
    return "\n".join(o)


def table(d):
    o = ['<div class="dirwrap"><table class="dirtable" id="dirtable">',
         '<thead><tr>' + "".join(f'<th>{e(c)}</th>' for c in d["columns"])
         + '</tr></thead><tbody>']
    for p in d["projects"]:
        attrs = [
            f'data-rank="{p["rank"]}"',
            f'data-name="{e(p["name"].lower())}"',
            f'data-score="{p["weighted_total"]}"',
            f'data-pillar="{e(p["pillar"])}"',
            f'data-segment="{e(p["segment"])}"',
            f'data-oss="{e(p["oss_status"])}"',
            f'data-licence_type="{e(p["licence_type"])}"',
            f'data-price_class="{e(p["price_class"])}"',
            f'data-maintenance_status="{e(p["maintenance_status"])}"',
            f'data-cost="{e(" ".join(cost_keys(p)))}"',
            f'data-licunres="{"1" if p["licence_type"] == "Unresolved" or p["oss_status"] == "Unverified" else "0"}"',
            f'data-search="{e(p["search"])}"',
        ]
        label = e(p["name"])
        if p["provisional"]:
            label += ' <span class="prov" title="Provisional assessment">provisional</span>'
        o.append("<tr " + " ".join(attrs) + ">"
                 f'<td class="num">{p["rank"]}</td>'
                 f'<td><a href="{e(p["page"][:-3])}.html">{label}</a>'
                 f'<br><code>{e(p["id"])}</code></td>'
                 f'<td class="what">{e(p["summary"])}</td>'
                 f'<td>{e(p["segment"])} · {e(p["subcategory"])}</td>'
                 f'<td><strong>{e(p["licence_type"])}</strong><br>'
                 f'<span class="lic">{e(p["licence_short"])}</span></td>'
                 f'<td title="{e(p["oss_detail"])}">{e(p["oss_status"])}</td>'
                 f'<td>{price_cell(p)}</td>'
                 f'<td>{cost_cell(p)}</td>'
                 f'<td>{e(p["maintenance_status"])}</td>'
                 "</tr>")
    o.append('</tbody></table></div>')
    return "\n".join(o)


SCRIPT = """
<script>
(function () {
  var tools = document.getElementById('dirtools');
  if (!tools) return;
  tools.hidden = false;                 /* controls appear only when this runs */
  var tbody = document.querySelector('#dirtable tbody');
  var rows = Array.prototype.slice.call(tbody.querySelectorAll('tr'));
  var total = rows.length;
  var q = document.getElementById('q');
  var sels = ['f-pillar', 'f-segment', 'f-oss', 'f-maint', 'f-sort', 'f-dir']
    .map(function (id) { return document.getElementById(id); });
  var pillar = sels[0], segment = sels[1], oss = sels[2], maint = sels[3],
      sort = sels[4], dir = sels[5];
  var licunres = document.getElementById('f-licunres');
  var chks = Array.prototype.slice.call(document.querySelectorAll('.costchk'));
  var count = document.getElementById('count');
  var segOpts = Array.prototype.slice.call(segment.options);

  function terms() {
    return (q.value || '').toLowerCase().split(/\\s+/).filter(Boolean);
  }

  function apply() {
    var ts = terms();
    var wantCost = chks.filter(function (c) { return c.checked; })
                       .map(function (c) { return c.value; });
    var shown = 0;
    rows.forEach(function (r) {
      var d = r.dataset, ok = true;
      if (pillar.value && d.pillar !== pillar.value) ok = false;
      if (ok && segment.value && d.segment !== segment.value) ok = false;
      if (ok && oss.value && d.oss !== oss.value) ok = false;
      if (ok && maint.value && d.maintenance_status !== maint.value) ok = false;
      if (ok && licunres.checked && d.licunres !== '1') ok = false;
      if (ok && wantCost.length) {
        var have = (d.cost || '').split(' ');
        ok = wantCost.some(function (w) { return have.indexOf(w) !== -1; });
      }
      if (ok && ts.length) {
        var hay = d.search;
        ok = ts.every(function (t) { return hay.indexOf(t) !== -1; });
      }
      r.hidden = !ok;
      if (ok) shown++;
    });
    /* Keep the segment menu honest about the chosen pillar. */
    segOpts.forEach(function (o) {
      o.hidden = !!(o.value && pillar.value &&
                    rows.filter(function (r) {
                      return r.dataset.segment === o.value;
                    }).some(function (r) { return r.dataset.pillar !== pillar.value; }));
    });
    count.textContent = 'Showing ' + shown + ' of ' + total + ' projects' +
      (shown === total ? '' : ' (filtered)');
    count.classList.toggle('filtered', shown !== total);
  }

  function resort() {
    var key = sort.value, desc = dir.value === 'desc';
    var numeric = key === 'rank' || key === 'score';
    rows.slice().sort(function (a, b) {
      var x = a.dataset[key], y = b.dataset[key], c;
      if (numeric) { c = (+x) - (+y); }
      else { c = String(x).localeCompare(String(y)); }
      if (c === 0) c = (+a.dataset.rank) - (+b.dataset.rank);
      return desc ? -c : c;
    }).forEach(function (r) { tbody.appendChild(r); });
  }

  function reset() {
    q.value = '';
    [pillar, segment, oss, maint].forEach(function (s) { s.value = ''; });
    sort.value = 'rank'; dir.value = 'asc';
    licunres.checked = false;
    chks.forEach(function (c) { c.checked = false; });
    resort(); apply();
  }

  q.addEventListener('input', apply);
  [pillar, segment, oss, maint].forEach(function (s) {
    s.addEventListener('change', apply);
  });
  chks.concat([licunres]).forEach(function (c) {
    c.addEventListener('change', apply);
  });
  [sort, dir].forEach(function (s) {
    s.addEventListener('change', function () { resort(); apply(); });
  });
  document.getElementById('reset').addEventListener('click', reset);
  apply();
})();
</script>
"""

